import matplotlib.pyplot as plt
import pandas as pd
import numpy as np

plt.figure(figsize=(15,10))
df = pd.read_csv('iris_data.csv')
a = df[df['Species'] == 'Iris-setosa']
b = df[df['Species'] == 'Iris-versicolor']
c = df[df['Species'] == 'Iris-virginica']


plt.subplot(2,3,1)
plt.scatter(a['SepalLengthCm'],a['SepalWidthCm'], color = 'blue', label= 'Iris-setosa')
plt.scatter(b['SepalLengthCm'],b['SepalWidthCm'], color = 'orange', label = 'Iris-versicolor')
plt.scatter(c['SepalLengthCm'],c['SepalWidthCm'], color = 'green',label = 'Iris-virginica')
k1,b1 = np.polyfit(a['SepalLengthCm'],a['SepalWidthCm'],1)
plt.plot(a['SepalLengthCm'],k1*a['SepalLengthCm']+b1,color = 'red')
k2,b2 = np.polyfit(b['SepalLengthCm'],b['SepalWidthCm'],1)
plt.plot(b['SepalLengthCm'],k2*b['SepalLengthCm']+b2,color = 'gray')
k3,b3 = np.polyfit(c['SepalLengthCm'],c['SepalWidthCm'],1)
plt.plot(c['SepalLengthCm'],k3*c['SepalLengthCm']+b3,color = 'black')
plt.xlabel('SepalLengthCm')
plt.ylabel('SepalWidthCm')
plt.grid(True)
plt.legend()

